"""Print data/docExtractResults.ts for the portfolio from the benchmark output, so no number is typed by hand.

    python scripts/site_results.py > ../ai-portfolio/data/docExtractResults.ts

Run after `python -m docextract report`. Marks the results interim until every configuration has scored all documents.
"""
from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from docextract.evaluate import score_doc  # noqa: E402
from docextract.schema import receipt_from_dict  # noqa: E402

RESULTS = Path(__file__).resolve().parents[1] / "results"
TOTAL_DOCS = 100
NAMES = {
    "ocr_rules": ("OCR + keyword rules", "No model. Finds totals only."),
    "ocr_llm": ("OCR + text model", "The classic two-stage pipeline."),
    "vision": ("Vision model", "Reads the image directly."),
    "verified": ("Vision + re-read", "Re-reads once when the arithmetic fails."),
}


def pct(x):
    return None if x is None else round(100 * x, 1)


def main() -> None:
    summary = json.loads((RESULTS / "summary.json").read_text())
    scored = summary["documents_scored"]
    configs = []
    for key, m in summary["configs"].items():
        if key == "verified":
            continue   # published only once it has scored the receipts that were flagged (see `final` below)
        name, note = NAMES[key]
        configs.append({
            "key": key, "name": name, "note": note,
            "total": [pct(m["total"]["accuracy"]), *[pct(v) for v in m["total"]["ci95"]]],
            "subtotal": [pct(m["subtotal"]["accuracy"]), *[pct(v) for v in m["subtotal"]["ci95"]]],
            "tax": [pct(m["tax"]["accuracy"]), *[pct(v) for v in m["tax"]["ci95"]]],
            "allFields": [pct(m["all_fields_correct"]["accuracy"]), *[pct(v) for v in m["all_fields_correct"]["ci95"]]],
            "itemF1": round(m["items"]["f1"], 2),
            "tokensPerReceipt": round(m["cost"]["tokens_per_doc"]),
        })

    rows = [json.loads(line) for line in (RESULTS / "vision.jsonl").read_text().splitlines() if line.strip()]
    cats = collections.Counter()
    for r in rows:
        g, p = receipt_from_dict(r["gold"]), receipt_from_dict(r["pred"])
        s = score_doc(p, g)
        for f, ok in s["fields"].items():
            if not ok:
                if getattr(p, f) is None:
                    cats[f"{f} left empty"] += 1
                elif (getattr(g, f) or 0) > 1e8:
                    cats["label error in the dataset"] += 1
                else:
                    cats[f"{f} misread"] += 1
        if s["items_tp"] < s["items_gold"] or s["items_pred"] > s["items_tp"]:
            cats["line items missed or extra"] += 1
    tokens = [r["prompt_tokens"] + r["completion_tokens"] for r in rows if r["prompt_tokens"]]
    verified_done = sum(1 for _ in (RESULTS / "verified.jsonl").open()) if (RESULTS / "verified.jsonl").exists() else 0
    final = scored >= TOTAL_DOCS and verified_done >= TOTAL_DOCS and len(rows) >= TOTAL_DOCS

    out = {
        "final": final, "documentsScored": scored, "documentsPlanned": TOTAL_DOCS, "visionDocuments": len(rows),
        "configs": configs,
        "visionFailures": [{"label": k, "documents": v} for k, v in cats.most_common()],
        "visionFlagged": sum(1 for r in rows if r["flagged"]),
        "visionTokensPerReceipt": round(sum(tokens) / len(tokens)) if tokens else None,
    }
    print("// GENERATED by scripts/site_results.py in the doc-extract repo from results/summary.json and vision.jsonl. Do not edit by hand.")
    print("export type DocxConfigResult = {")
    print("  key: string; name: string; note: string;")
    print("  /** [percent right, 95% interval low, high] */")
    print("  total: number[]; subtotal: number[]; tax: number[]; allFields: number[];")
    print("  itemF1: number; tokensPerReceipt: number;")
    print("};")
    print(f"export const DOCX_BENCH: {{ final: boolean; documentsScored: number; documentsPlanned: number; visionDocuments: number; configs: DocxConfigResult[]; visionFailures: {{ label: string; documents: number }}[]; visionFlagged: number; visionTokensPerReceipt: number | null }} = {json.dumps(out, indent=2)};")


if __name__ == "__main__":
    main()
